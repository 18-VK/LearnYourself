import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

const counts = z.object({
  headings: z.number(),
  code: z.number(),
  htmlAsCode: z.number(),
  tables: z.number(),
  words: z.number(),
  codeWords: z.number(),
});

const resource = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('asset'),
    file: z.string(),
    slug: z.string(),
    title: z.string(),
    kind: z.enum(['image', 'pdf', 'document']),
    authorship: z.string(),
    credit: z.string().nullable(),
    alt: z.string().nullable(),
    usedBy: z.string().nullable(),
    src: z.string().optional(),
    srcset: z.string().optional(),
    width: z.number().optional(),
    height: z.number().optional(),
    page: z.string().optional(),
  }),
  z.object({ type: z.literal('link'), url: z.string(), title: z.string(), from: z.string() }),
  z.object({ type: z.literal('tryLocally'), path: z.string(), url: z.string() }),
]);

/** Generated by scripts/build-content.ts from the notes; never edit these files by hand. */
const lessons = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/lessons' }),
  schema: z.object({
    title: z.string(),
    course: z.string(),
    courseTitle: z.string(),
    module: z.string(),
    moduleTitle: z.string(),
    lesson: z.string(),
    kind: z.enum(['lesson', 'checklist', 'roadmap']),
    order: z.number(),
    minutes: z.number(),
    objectives: z.array(z.string()),
    objectivesDerived: z.boolean(),
    sources: z.array(z.object({ file: z.string(), lines: z.string(), url: z.string() })),
    related: z.array(z.object({ id: z.string(), title: z.string(), course: z.string(), courseTitle: z.string() })),
    cheatsheets: z.array(z.object({ id: z.string(), title: z.string() })),
    resources: z.array(resource),
    interviewHeadings: z.array(z.string()),
    nodeLinks: z.record(z.string(), z.array(z.string())),
    vizCount: z.number(),
    counts: z.object({ source: counts, generated: counts, recovered: z.number(), markers: z.record(z.string(), z.number()) }),
  }),
});

const landing = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/landing' }),
  schema: z.object({ course: z.string(), sources: z.array(z.object({ file: z.string(), url: z.string() })) }),
});

export const collections = { lessons, landing };
