import fs from 'node:fs';
import type { DataSummary } from './data-check';
import { COVERAGE_REPORT } from './paths';

export interface NoteCoverage {
  file: string;
  targets: string[];
  status: 'mapped' | 'unmapped';
}
export interface LessonCoverage {
  id: string;
  title: string;
  sources: string[];
  source: { headings: number; code: number; recovered: number; htmlAsCode: number; tables: number };
  markers: Record<string, number>;
  minutes: number;
}
export interface OutputCounts {
  headings: number;
  code: number;
  tables: number;
  markers: Record<string, number>;
  ok: boolean;
  problems: string[];
}
export interface CoverageData {
  notes: NoteCoverage[];
  lessons: LessonCoverage[];
  excluded: { file: string; reason: string }[];
  duplicates: { file: string; duplicateOf: string; reason: string }[];
  linkOnly: { file: string; usedBy: string; reason: string }[];
  interview: { file: string; from?: string; reason: string }[];
  omitted: { file: string; lines: string; text: string }[];
  recovered: { file: string; lines: string; lang: string; first: string; label: boolean }[];
  planned: { id: string; title: string; noteFolder: string }[];
  assets: { file: string; publish: boolean; mode: string | null; credit: string | null }[];
  errors: string[];
  warnings?: string[];
  /** Quizzes, cheat sheets and interview questions (src/data/*). */
  data?: DataSummary;
  /** Filled in by verify-output after the build: lesson id → counts found in the rendered HTML. */
  output: Record<string, OutputCounts> | null;
}

const esc = (s: string) => s.replace(/\|/g, '\\|');

export function writeCoverage(d: CoverageData): void {
  const mapped = d.notes.filter((n) => n.status === 'mapped').length;
  const out = d.output;
  const mismatches = out ? Object.entries(out).filter(([, o]) => !o.ok) : [];
  const L: string[] = [];
  L.push('# Coverage report', '');
  L.push('Generated by `scripts/build-content.ts` (sources) and `scripts/verify-output.ts` (rendered output). Do not edit by hand.', '');
  L.push('## Summary', '');
  L.push('| Check | Result |', '|---|---|');
  L.push(`| Notes in the repo | ${d.notes.length} |`);
  L.push(`| Notes mapped or explicitly excluded | ${mapped} of ${d.notes.length}${mapped === d.notes.length ? ' ✅' : ' ❌'} |`);
  L.push(`| Lessons | ${d.lessons.length} |`);
  L.push(`| Recovered code blocks (unfenced code rendered as code) | ${d.recovered.length} |`);
  L.push(`| Lines omitted on purpose | ${d.omitted.length} entries |`);
  L.push(`| Planned modules (coming soon) | ${d.planned.length} |`);
  L.push(`| Source vs output counts | ${out ? (mismatches.length ? `${mismatches.length} mismatch(es) ❌` : 'all lessons match ✅') : 'not checked yet (run the build)'} |`);
  L.push(`| Pipeline errors | ${d.errors.length ? `${d.errors.length} ❌` : 'none ✅'} |`, '');

  if (d.errors.length) {
    L.push('## Errors', '');
    for (const e of d.errors) L.push('```text', e, '```', '');
  }
  if (d.warnings?.length) {
    L.push('## Warnings', '', 'Not build failures, but work left to do.', '');
    for (const w of d.warnings) L.push(`- ${esc(w)}`);
    L.push('');
  }
  if (d.data) {
    const q = d.data;
    L.push('## Quizzes, cheat sheets and interview questions', '');
    L.push('| Data | Count |', '|---|---|');
    L.push(`| Lessons with a quiz | ${q.quizzes.lessons} (${q.quizzes.questions} questions)${q.quizzes.missing.length ? `; ${q.quizzes.missing.length} teaching lesson(s) without one` : ' ✅'} |`);
    L.push(`| Cheat sheets | ${q.cheatsheets.sheets} (${q.cheatsheets.items} items, ${q.cheatsheets.fromDocs} from docs)${q.cheatsheets.missing.length ? `; missing: ${q.cheatsheets.missing.join(', ')}` : ' ✅'} |`, '');
    L.push('| Interview topic | From notes | Web-researched | Reviewed |', '|---|---|---|---|');
    for (const t of q.interview) L.push(`| ${t.topic} | ${t.notes} | ${t.web} | ${t.reviewed} |`);
    L.push('');
    if (q.quizzes.missing.length) L.push(`Lessons without a quiz: ${q.quizzes.missing.join(', ')}`, '');
  }

  L.push('## Every note', '', '| Note | Goes to |', '|---|---|');
  for (const n of d.notes) L.push(`| \`${esc(n.file)}\` | ${n.status === 'unmapped' ? '❌ **unmapped**' : esc(n.targets.join('<br>'))} |`);
  L.push('');

  L.push('## Lessons: source vs rendered output', '');
  L.push('Source counts come from the notes (after intentional omissions). Code = fenced blocks + recovered blocks + raw HTML/XAML blocks shown as code.', '');
  L.push('| Lesson | Min | Headings (src → out) | Code (src → out) | Tables (src → out) | ❌/✅/👉 markers (src → out) | OK |', '|---|---|---|---|---|---|---|');
  for (const l of d.lessons) {
    const o = out?.[l.id];
    const codeSrc = l.source.code + l.source.recovered + l.source.htmlAsCode;
    const mk = (m: Record<string, number>) => `${m['❌'] ?? 0}/${m['✅'] ?? 0}/${m['👉'] ?? 0}`;
    L.push(
      `| \`${l.id}\` | ${l.minutes} | ${l.source.headings} → ${o?.headings ?? '…'} | ${codeSrc}${l.source.recovered ? ` (${l.source.recovered} recovered)` : ''} → ${o?.code ?? '…'} | ${l.source.tables} → ${o?.tables ?? '…'} | ${mk(l.markers)} → ${o ? mk(o.markers) : '…'} | ${o ? (o.ok ? '✅' : '❌ ' + esc(o.problems.join('; '))) : '…'} |`,
    );
  }
  L.push('');

  L.push('## Lines omitted on purpose', '', 'Leftover chatbot offers, dropped from the site by decision (see `_site.yaml` → `omitLines`). The notes keep them.', '');
  L.push('| Note | Line(s) | Text |', '|---|---|---|');
  for (const o of d.omitted) L.push(`| \`${esc(o.file)}\` | ${o.lines} | ${esc(o.text)} |`);
  L.push('');

  L.push('## Recovered code blocks', '', 'Code written as plain text in the notes, rendered as code blocks. Check these if a block looks wrong.', '');
  L.push('| Note | Lines | Language | Starts with |', '|---|---|---|---|');
  for (const r of d.recovered) L.push(`| \`${esc(r.file.split('/').pop() ?? r.file)}\` | ${r.lines} | ${r.lang}${r.label ? ' (from label line)' : ''} | \`${esc(r.first.replace(/`/g, "'"))}\` |`);
  L.push('');

  L.push('## Excluded notes', '', '| Note | Reason |', '|---|---|');
  for (const x of d.excluded) L.push(`| \`${esc(x.file)}\` | ${esc(x.reason)} |`);
  L.push('', '## Verified duplicates', '', '| Note | Duplicate of | Reason |', '|---|---|---|');
  for (const x of d.duplicates) L.push(`| \`${esc(x.file)}\` | \`${esc(x.duplicateOf)}\` | ${esc(x.reason.trim())} |`);
  L.push('', '## Link-only notes', '', '| Note | Shown on | Reason |', '|---|---|---|');
  for (const x of d.linkOnly) L.push(`| \`${esc(x.file)}\` | \`${x.usedBy}\` | ${esc(x.reason)} |`);
  L.push('', '## Routed to Interview Prep', '', '| Note | Section | Reason |', '|---|---|---|');
  for (const x of d.interview) L.push(`| \`${esc(x.file)}\` | ${esc(x.from ?? 'whole file')} | ${esc(x.reason)} |`);
  L.push('', '## Planned modules (coming soon)', '', '| Module | Note folder |', '|---|---|');
  for (const p of d.planned) L.push(`| \`${p.id}\` ${esc(p.title)} | \`${esc(p.noteFolder)}\` |`);
  L.push('', '## Binary files', '', '| File | Published | Mode | Credit |', '|---|---|---|---|');
  for (const a of d.assets) L.push(`| \`${esc(a.file)}\` | ${a.publish ? 'yes' : 'no'} | ${a.mode ?? '—'} | ${esc(a.credit ?? '—')} |`);
  L.push('');
  fs.writeFileSync(COVERAGE_REPORT, L.join('\n'));
}
